#!/usr/bin/env python3
"""Build flash-resident button waveforms from confirmed capture annotations."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def build_entries(buttons, captures):
    samples = {c['device_capture_id']: c for c in captures}
    entries = []
    names = set()
    for button in buttons:
        if button['annotation_status'] not in ('user_confirmed', 'user_order_confirmed'):
            continue
        if button['id'] in names:
            raise ValueError('Duplicate button id')
        names.add(button['id'])
        expected_codes = button.get('frame_codes', [button['code']] * button['frame_count'])
        if not button['capture_ids'] or len(expected_codes) != button['frame_count']:
            raise ValueError('Missing capture or inconsistent frame count')
        for capture_id in button['capture_ids']:
            capture = samples[capture_id]
            a = capture['analysis']
            frames = a.get('frames', [])
            raw = capture['raw_us']
            if not (a['complete'] and len(frames) == button['frame_count']
                    and all(f.get('inverse_valid') for f in frames)
                    and [f.get('code') for f in frames] == expected_codes
                    and len(raw) == capture['count'] and len(raw) % 2 == 1
                    and all(0 < t <= 65535 for t in raw)):
                raise ValueError(f'Unsafe/incomplete replay sample {capture_id} for {button["id"]}')
        capture_id = button['capture_ids'][0]
        raw = samples[capture_id]['raw_us']
        entries.append({'index': len(entries) + 1, 'id': button['id'], 'code': button['code'],
                        'frame_count': button['frame_count'], 'frame_codes': expected_codes,
                        'representative_capture_id': capture_id,
                        'raw_us': raw})
    return entries


def main():
    catalog_path = ROOT / 'captures/york-button-catalog.json'
    catalog = json.loads(catalog_path.read_text())
    captures = json.loads((ROOT / catalog['source']).read_text())['captures']
    entries = build_entries(catalog['buttons'], captures)
    if not entries:
        raise ValueError('No confirmed button captures')
    tag = hashlib.sha256(json.dumps(entries, sort_keys=True).encode()).hexdigest()[:12]
    lines = ['// Generated by scripts/generate_replay_catalog.py; do not edit.', '#pragma once',
             '#include <avr/pgmspace.h>', f'#define BUTTON_CATALOG_TAG "{tag}"',
             'struct CapturedButton { const uint16_t *timings; uint16_t count; };']
    for entry in entries:
        macro_name = entry['id'].upper().replace('-', '_')
        if not macro_name.replace('_', '').isalnum():
            raise ValueError('Invalid button identifier for C++ macro')
        lines.append(f'#define BUTTON_INDEX_{macro_name} {entry["index"]}')
        lines.append(f'// {entry["index"]}: {entry["id"]}; capture {entry["representative_capture_id"]}')
        lines.append(f'const uint16_t kButton{entry["index"]}[] PROGMEM = {{')
        raw = entry['raw_us']
        for start in range(0, len(raw), 16):
            lines.append('  ' + ', '.join(map(str, raw[start:start + 16])) + ',')
        lines.append('};')
    lines.append('const CapturedButton kCapturedButtons[] PROGMEM = {')
    for entry in entries:
        lines.append(f'  {{kButton{entry["index"]}, {len(entry["raw_us"])}}},')
    lines += ['};', f'constexpr uint8_t kCapturedButtonCount = {len(entries)};', '']
    header = ROOT / 'sketches/ACStateControl/CapturedButtons.h'
    header.write_text('\n'.join(lines))
    index = {'catalog_tag': tag, 'carrier_setting_khz': 38,
             'note': 'One original captured burst per PRESS; no added repeats. Check firmware catalog tag before sending. Does not imply UNO replay tested.',
             'buttons': []}
    for entry in entries:
        item = {k: v for k, v in entry.items() if k != 'raw_us'}
        item['duration_us'] = sum(entry['raw_us'])
        item['serial_command_template'] = f'PRESS <sequence> {entry["index"]}'
        index['buttons'].append(item)
    (ROOT / 'captures/york-replay-index.json').write_text(json.dumps(index, ensure_ascii=False, indent=2) + '\n')
    print(f'Generated {len(entries)} captured button waveforms; catalog {tag}')


if __name__ == '__main__':
    main()
